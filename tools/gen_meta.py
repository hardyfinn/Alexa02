#!/usr/bin/env python3
"""Writes src/ParamMeta.hpp from the firmware sources in src/lxr.

It reads the parameter list (Inc/Parameters.h) and the parameter display
types (the firmware's menu.c table, copied below as PARAM_TYPES so the menu
code itself doesn't have to be vendored). Run from the repository root:
    python3 tools/gen_meta.py
"""
import re, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HDR = os.path.join(ROOT, "src/lxr/Inc/Parameters.h")

src = open(HDR).read()
src = re.sub(r"/\*.*?\*/", "", src, flags=re.S)
src = re.sub(r"//[^\n]*", "", src)
body = src[src.index("{", src.index("enum")) + 1:]
body = body[:body.index("}")]
names = {}   # name -> value
order = []
idx = 0
for tok in body.split(","):
    tok = tok.strip()
    if not tok:
        continue
    if "=" in tok:
        n, v = [x.strip() for x in tok.split("=", 1)]
        idx = names[v] if v in names else int(eval(v))
    else:
        n = tok
    names[n] = idx
    order.append((n, idx))
    idx += 1

END = names["END_OF_SOUND_PARAMETERS"]

# display types from the firmware's menu.c (parameter_dtypes), sound params only.
# R = 0..127, P = -63..63 (stored 0..127), M:<list> = named choices, O = on/off,
# C = 0..100, T = mod target, N = note (unused here)
types = {}
def t(name, kind):
    types[names[name]] = kind
for v in range(END):
    types[v] = "R"
for n in ["PAR_OSC_WAVE_DRUM1", "PAR_OSC_WAVE_DRUM2", "PAR_OSC_WAVE_DRUM3", "PAR_OSC_WAVE_SNARE",
          "PAR_WAVE1_CYM", "PAR_WAVE1_HH", "PAR_MOD_WAVE_DRUM1", "PAR_MOD_WAVE_DRUM2", "PAR_MOD_WAVE_DRUM3",
          "PAR_WAVE2_CYM", "PAR_WAVE3_CYM", "PAR_WAVE2_HH", "PAR_WAVE3_HH", "PAR_FX_WAVE"]:
    t(n, "M:WAVE")
for i in range(1, 7):
    t(f"PAR_COARSE{i}", "P"); t(f"PAR_FINE{i}", "P")
for n in ["PAR_MOD_OSC_F1_CYM", "PAR_MOD_OSC_F2_CYM", "PAR_MOD_OSC_F1", "PAR_MOD_OSC_F2",
          "PAR_FM_FREQ1", "PAR_FM_FREQ2", "PAR_FM_FREQ3"]:
    t(n, "P")
for i in range(1, 7):
    t(f"PAR_PAN{i}", "P")
for i in range(1, 4):
    t(f"PAR_MIX_MOD_{i}", "M:MIXFM")
for i in range(1, 7):
    t(f"PAR_VOLUME_MOD_ON_OFF{i}", "O")
    t(f"PAR_WAVE_LFO{i}", "M:LFOWAVE")
    t(f"PAR_RETRIGGER_LFO{i}", "M:RETRIG")
    t(f"PAR_SYNC_LFO{i}", "M:SYNC")
    t(f"PAR_FILTER_TYPE_{i}", "M:FILTER")
    t(f"PAR_TRANS{i}_WAVE", "M:TRANS")
    t(f"PAR_AUDIO_OUT{i}", "M:OUT")
t("PAR_FX_TYPE", "M:FX")
t("PAR_FX_ROUTING", "M:OUTFX")
t("PAR_FX_DRY_WET", "C")
t("PAR_FX_DIST_TYPE", "M:DIST")
t("PAR_FX_RATIO", "M:RATIO")
t("PAR_FX_REVERB_TYPE", "M:REVERB")
t("PAR_FX_DELAY_TYPE", "M:DELAY")
for i in range(1, 19):
    t(f"PAR_CV_DEST_{i}", "T")
    t(f"PAR_CV_MOD_AMT_{i}", "C")
    t(f"PAR_CV_SRC_{i}", "M:CVSRC")

out = []
w = out.append
w("// Generated by tools/gen_meta.py from the LXR firmware headers. Do not edit.")
w("#pragma once")
w("")
w("namespace lxr {")
w("")
w(f"static const int KIT_SIZE = {END};")
w("")
seen = set()
for n, v in order:
    if n in seen or not n.startswith("PAR_"):
        continue
    seen.add(n)
    if v <= END + 1:
        w(f"static const int {n} = {v};")
w("")
w("enum ParamKind { K_RANGE, K_PM63, K_MENU, K_ONOFF, K_PCT, K_TARGET };")
w("enum MenuList { L_NONE, L_WAVE, L_MIXFM, L_LFOWAVE, L_RETRIG, L_SYNC, L_FILTER, L_TRANS, L_OUT, L_OUTFX, L_FX, L_DIST, L_RATIO, L_REVERB, L_DELAY, L_CVSRC };")
w("")
w("struct ParamKindInfo { unsigned char kind; unsigned char list; };")
w("static const ParamKindInfo PARAM_KINDS[KIT_SIZE] = {")
row = []
for v in range(END):
    k = types[v]
    if k == "R": row.append("{K_RANGE,L_NONE}")
    elif k == "P": row.append("{K_PM63,L_NONE}")
    elif k == "O": row.append("{K_ONOFF,L_NONE}")
    elif k == "C": row.append("{K_PCT,L_NONE}")
    elif k == "T": row.append("{K_TARGET,L_NONE}")
    else: row.append("{K_MENU,L_" + k[2:] + "}")
for i in range(0, len(row), 6):
    w("\t" + ", ".join(row[i:i + 6]) + ",")
w("};")
w("")
w("} // namespace lxr")
open(os.path.join(ROOT, "src/ParamMeta.hpp"), "w").write("\n".join(out) + "\n")
print("wrote src/ParamMeta.hpp,", END, "parameters")
