#!/usr/bin/env python3
"""Writes src/FactoryKits.hpp: the firmware's init kit plus the Alexa02 kits
defined in tools/kits.py (each one is the init kit with some values changed).
    python3 tools/make_kits.py
"""
import os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))

# parameter numbers from the generated metadata
meta = open(os.path.join(ROOT, "src/ParamMeta.hpp")).read()
P = {m.group(1): int(m.group(2)) for m in re.finditer(r"static const int (PAR_\w+) = (\d+);", meta)}
KIT_SIZE = int(re.search(r"KIT_SIZE = (\d+)", meta).group(1))

src = open(os.path.join(ROOT, "src/lxr/Src/initKit.c")).read()
nums = [int(x, 0) for x in re.findall(r"0x[0-9a-fA-F]+|\b\d+\b", src[src.index("{"):])]
init = nums[8:] + [0] * (KIT_SIZE - (len(nums) - 8))
init = init[:KIT_SIZE]

import kits
out = [("Init (firmware)", "Initkit", init)]
for title, name, changes in kits.KITS:
    k = list(init)
    for key, val in changes.items():
        k[P[key]] = val
    out.append((title, name, k))

lines = ["// Generated by tools/make_kits.py. Do not edit.", "#pragma once", "#include <cstdint>", "",
         "namespace lxr {", "", "struct FactoryKit { const char* title; const uint8_t* data; int size; };", ""]
for i, (title, name, k) in enumerate(out):
    data = list(name.encode()[:8].ljust(8, b"\0")) + k
    lines.append(f"static const uint8_t FACTORY_KIT_{i}[{len(data)}] = {{")
    for j in range(0, len(data), 24):
        lines.append("\t" + ", ".join(str(x) for x in data[j:j + 24]) + ",")
    lines.append("};")
lines.append("")
lines.append(f"static const int NUM_FACTORY_KITS = {len(out)};")
lines.append("static const FactoryKit FACTORY_KITS[NUM_FACTORY_KITS] = {")
for i, (title, name, k) in enumerate(out):
    lines.append(f'\t{{"{title}", FACTORY_KIT_{i}, {8 + len(k)}}},')
lines.append("};")
lines.append("")
lines.append("} // namespace lxr")
open(os.path.join(ROOT, "src/FactoryKits.hpp"), "w").write("\n".join(lines) + "\n")
print("wrote", len(out), "kits")
